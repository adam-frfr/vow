function theme(
  id: string,
  name: string,
  collection: CollectionId,
  template: TemplateId,
  hero: string,
  layout: HeroLayout,
  [bg, surface, text, muted, accent, onAccent]: Pal,
  [display, body, script]: Fonts,
  description: string,
  tags: string[],
  x: Extra = {},
): Theme {
  return {
    id, name, collection, template, hero, layout, description, tags,
    palette: { bg, surface, text, muted, accent, onAccent },
    fonts: { display, body, script },
    decor: x.decor, effects: x.fx, stickers: x.stickers,
  };
}

/** A painted wreath/frame holds the names (Atelier). */
const atelier = (id: string, name: string, c: CollectionId, frame: string, pal: Pal, f: Fonts, d: Omit<Decor, "heroFloral">, desc: string, tags: string[], fx?: Effects, dark = false) =>
  theme(id, name, c, "atelier", LIB(frame), dark ? "poster" : "botanical", pal, f, desc, tags, { decor: { heroFloral: frame, ink: true, ...d }, fx });

/** One painted bouquet as a museum plate (Botanical). */
const plate = (id: string, name: string, c: CollectionId, art: string, pal: Pal, f: Fonts, d: Decor, desc: string, tags: string[], fx?: Effects) =>
  theme(id, name, c, "botanical", LIB(art), "botanical", pal, f, desc, tags, { decor: d, fx });

/** A painted pattern as the envelope liner (Stationery), with an optional posy tucked on the card. */
const suite = (id: string, name: string, c: CollectionId, pattern: string, pal: Pal, f: Fonts, desc: string, tags: string[], posy?: string, fx?: Effects, d: Decor = {}) =>
  theme(id, name, c, "stationery", LIB(pattern), "card", pal, f, desc, tags, {
    decor: d,
    fx,
    stickers: posy ? [{ id: "posy", asset: posy, anchor: "top", x: 66, y: 64, w: 17, r: 8, anim: "ink" }] : undefined,
  });

const corners = (art: string, w = 24): Sticker[] => [
  { id: "c1", asset: art, anchor: "top", x: 6, y: 9, w, r: 180, anim: "ink" },
  { id: "c2", asset: art, anchor: "top", x: 94, y: 92, w, r: 0, anim: "ink" },
];


import type { CollectionId, HeroLayout, Theme } from "./themes";

const U = (id: string) => `https://images.unsplash.com/${id}`;
const WM = (path: string) => `https://upload.wikimedia.org/wikipedia/commons/${path}`;
const WMT = (path: string) => `https://upload.wikimedia.org/wikipedia/commons/thumb/${path}`;

type Pal = [bg: string, surface: string, text: string, muted: string, accent: string, onAccent: string];
type Fonts = [display: string, body: string, script?: string];

function mk(
  id: string,
  name: string,
  collection: CollectionId,
  layout: HeroLayout,
  hero: string,
  [bg, surface, text, muted, accent, onAccent]: Pal,
  [display, body, script]: Fonts,
  description: string,
  tags: string[],
  opts: Partial<Pick<Theme, "extras" | "heroFilter" | "displayCase" | "overlay">> = {},
): Theme {
  return {
    id,
    name,
    collection,
    layout,
    hero,
    palette: { bg, surface, text, muted, accent, onAccent },
    fonts: { display, body, script },
    description,
    tags,
    overlay: layout === "fullbleed" || layout === "cover" || layout === "card" ? "dark" : undefined,
    ...opts,
  };
}

